UPDATE account          SET type = 'WEALTH' WHERE type = 'FUND';
UPDATE account_template SET type = 'WEALTH', display_name = '蚂蚁财富 / 京东金融(基金)'
 WHERE code = 'ant_fortune' AND type = 'FUND';
